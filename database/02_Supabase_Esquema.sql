-- Supabase Auth vincula la identidad firmada con el perfil activo de la app.
CREATE OR REPLACE FUNCTION public."UsuarioActualTieneAcceso"()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public."Tbl_Usuarios" AS u
        WHERE u."AuthUserId" = auth.uid()
          AND u."Estado" IS TRUE
          AND (u."EsDueno" IS TRUE OR u."TipoUsuario" = 'Administrador')
    );
$$;

REVOKE ALL ON FUNCTION public."UsuarioActualTieneAcceso"() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public."UsuarioActualTieneAcceso"() TO authenticated;

-- Limpiar los permisos de tabla predeterminados antes de otorgar el mínimo.
-- RLS controla filas; estos GRANT controlan operaciones permitidas sobre tablas.
REVOKE ALL PRIVILEGES ON ALL TABLES IN SCHEMA public FROM anon, authenticated;
GRANT USAGE ON SCHEMA public TO authenticated;

ALTER TABLE public."Tbl_Usuarios" ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON TABLE public."Tbl_Usuarios" TO authenticated;
REVOKE INSERT, UPDATE, DELETE ON TABLE public."Tbl_Usuarios" FROM anon, authenticated;
CREATE POLICY "Tbl_Usuarios_lectura_activa"
    ON public."Tbl_Usuarios" FOR SELECT TO authenticated
    USING (public."UsuarioActualTieneAcceso"());

-- El cliente no puede borrar fisicamente ni administrar identidades Auth.
-- INSERT/UPDATE de usuarios pasan por una funcion de servidor que valida al actor
-- y protege el perfil EsDueno; la clave service_role nunca se incluye en WinForms.
DO $$
DECLARE
    nombre_tabla text;
BEGIN
    FOREACH nombre_tabla IN ARRAY ARRAY[
        'Tbl_Sucursales', 'Tbl_Empleados', 'Tbl_Clientes', 'Tbl_Planes',
        'Tbl_Lineas', 'Tbl_Proveedores', 'Tbl_Marcas', 'Tbl_Equipos',
        'Tbl_Compras', 'Tbl_DetalleCompra', 'Tbl_Inventario', 'Tbl_Ventas',
        'Tbl_DetalleVenta', 'Tbl_Facturacion', 'Tbl_DetalleFactura',
        'Tbl_Pagos', 'Tbl_Cardex', 'Tbl_Reclamos'
    ]
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', nombre_tabla);
        EXECUTE format('GRANT SELECT, INSERT, UPDATE ON TABLE public.%I TO authenticated', nombre_tabla);
        EXECUTE format('REVOKE DELETE ON TABLE public.%I FROM anon, authenticated', nombre_tabla);

        EXECUTE format(
            'CREATE POLICY %I ON public.%I FOR SELECT TO authenticated USING (public."UsuarioActualTieneAcceso"())',
            nombre_tabla || '_lectura', nombre_tabla);
        EXECUTE format(
            'CREATE POLICY %I ON public.%I FOR INSERT TO authenticated WITH CHECK (public."UsuarioActualTieneAcceso"())',
            nombre_tabla || '_alta', nombre_tabla);
        EXECUTE format(
            'CREATE POLICY %I ON public.%I FOR UPDATE TO authenticated USING (public."UsuarioActualTieneAcceso"()) WITH CHECK (public."UsuarioActualTieneAcceso"())',
            nombre_tabla || '_edicion', nombre_tabla);
    END LOOP;
END;
$$;

REVOKE ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

COMMIT;
